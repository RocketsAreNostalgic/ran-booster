import { createHash } from 'node:crypto';
import { readFile, realpath, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/*
 * WordPress 7.1 registers a `wp-theme` style that defines the --wpds-* design
 * tokens (type scale, colour, spacing) which the public @wordpress/ui styles read.
 * Earlier WordPress has no such style, so Booster ships the same tokens for them.
 * They come from the @wordpress/theme release that the pinned @wordpress/ui
 * depends on, so the bundled tokens always match the extracted component styles.
 *
 * Usage: node scripts/build-wpds-tokens.mjs [--check]
 */
const out = 'assets/lib/ran-booster-wpds-tokens.css';
const manifestOut = out.replace(/\.css$/, '.json');
const uiRoot = await realpath('node_modules/@wordpress/ui');
const themeRoot = join(uiRoot, '..', 'theme');
const source = await readFile(
	join(themeRoot, 'prebuilt/css/design-tokens.css'),
	'utf8'
);
const { name, version } = JSON.parse(
	await readFile(join(themeRoot, 'package.json'), 'utf8')
);
const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const tokens = [...new Set(source.match(/--wpds-[a-z0-9-]+(?=\s*:)/g))].sort();
if (name !== '@wordpress/theme' || tokens.length < 100) {
	throw new Error(
		`Unexpected design token source: ${name} with ${tokens.length} tokens`
	);
}
const css = `/* ${name} ${version} design tokens, bundled for WordPress before 7.1 (no wp-theme style). Generated by scripts/build-wpds-tokens.mjs; do not edit. */\n${source}`;
const json = `${JSON.stringify(
	{
		source: { package: name, version, sha256: sha256(source) },
		tokens: tokens.length,
		outputSha256: sha256(css),
	},
	null,
	'\t'
)}\n`;

if (process.argv.includes('--check')) {
	for (const [path, expected] of [
		[out, css],
		[manifestOut, json],
	]) {
		if ((await readFile(path, 'utf8')) !== expected) {
			throw new Error(`Design token output differs: ${path}`);
		}
	}
} else {
	await writeFile(out, css);
	await writeFile(manifestOut, json);
}
process.stdout.write(
	`Design tokens: ${tokens.length} from ${name} ${version}, ${Buffer.byteLength(css)} bytes\n`
);
